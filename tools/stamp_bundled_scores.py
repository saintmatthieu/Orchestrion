import json
import sys
from pathlib import Path

SCORES = Path(__file__).resolve().parents[1] / "scores"


def main():
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} <rolls checkout>")
    tools = Path(sys.argv[1]).resolve() / "tools"
    if not (tools / "build.py").exists():
        sys.exit(f"{tools.parent} is not a Rolls checkout")
    sys.path.insert(0, str(tools))
    import build
    import difficulty

    model = json.loads(difficulty.MODEL.read_text(encoding="utf-8"))
    for mxl in sorted(SCORES.glob("*.mxl")):
        levels = {**difficulty.levels(difficulty.measures(mxl), model),
                  "method": model["method"]}
        build.stamp(mxl, None, levels)
        print(f"{mxl.name}: rhythm {levels['rhythm']}, notes {levels['notes']}")


if __name__ == "__main__":
    main()
